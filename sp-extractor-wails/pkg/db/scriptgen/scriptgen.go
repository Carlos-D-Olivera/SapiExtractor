// Package scriptgen builds DDL and DML scripts from table metadata. It is pure
// (no database access) so it can be unit-tested for every dialect.
package scriptgen

import (
	"fmt"
	"strings"

	"sp-extractor-wails/pkg/db"
)

// Generate returns every script available for the table, in display order.
func Generate(dbType db.DatabaseType, m db.TableMeta) []db.TableScript {
	g := gen{t: dbType, m: m}
	create := g.createTable()
	indexes := g.indexes()
	fks := g.foreignKeys()

	full := []string{create}
	if indexes != "" {
		full = append(full, indexes)
	}
	if fks != "" {
		full = append(full, fks)
	}

	scripts := []db.TableScript{
		{ID: "ddl", Label: "DDL completo", SQL: strings.Join(full, "\n\n")},
		{ID: "create", Label: "CREATE TABLE", SQL: create},
	}
	if indexes != "" {
		scripts = append(scripts, db.TableScript{ID: "indexes", Label: "Índices", SQL: indexes})
	}
	if fks != "" {
		scripts = append(scripts, db.TableScript{ID: "fks", Label: "Llaves foráneas", SQL: fks})
	}
	scripts = append(scripts,
		db.TableScript{ID: "select", Label: "SELECT", SQL: g.selectAll()},
		db.TableScript{ID: "selectpk", Label: "SELECT por PK", SQL: g.selectByPK()},
		db.TableScript{ID: "insert", Label: "INSERT", SQL: g.insert()},
		db.TableScript{ID: "update", Label: "UPDATE", SQL: g.update()},
		db.TableScript{ID: "delete", Label: "DELETE", SQL: g.delete()},
	)
	return scripts
}

type gen struct {
	t db.DatabaseType
	m db.TableMeta
}

func (g gen) quote(id string) string {
	switch g.t {
	case db.MySQL:
		return "`" + strings.ReplaceAll(id, "`", "``") + "`"
	case db.PostgreSQL:
		return `"` + strings.ReplaceAll(id, `"`, `""`) + `"`
	default:
		return "[" + strings.ReplaceAll(id, "]", "]]") + "]"
	}
}

func (g gen) qualified(schema, name string) string {
	// In MySQL the "schema" is the database itself; omit it so scripts are portable across databases.
	if schema == "" || g.t == db.MySQL {
		return g.quote(name)
	}
	return g.quote(schema) + "." + g.quote(name)
}

func (g gen) table() string { return g.qualified(g.m.Schema, g.m.Name) }

func (g gen) quoteList(cols []string) string {
	q := make([]string, len(cols))
	for i, c := range cols {
		q[i] = g.quote(c)
	}
	return strings.Join(q, ", ")
}

func (g gen) param(col string) string {
	if g.t == db.PostgreSQL {
		return ":" + col
	}
	return "@" + col
}

func (g gen) batchEnd() string {
	if g.t == db.SQLServer {
		return "\nGO"
	}
	return ""
}

func (g gen) createTable() string {
	if len(g.m.Columns) == 0 {
		return "-- No se pudieron extraer columnas para la tabla."
	}
	var lines []string
	for _, c := range g.m.Columns {
		line := "    " + g.quote(c.Name) + " " + c.DataType
		switch g.t {
		case db.SQLServer:
			if c.Identity {
				line += fmt.Sprintf(" IDENTITY(%d,%d)", orOne(c.IdentitySeed), orOne(c.IdentityStep))
			}
		case db.MySQL:
			if c.Identity {
				line += " AUTO_INCREMENT"
			}
		case db.PostgreSQL:
			if c.Identity {
				line += " GENERATED BY DEFAULT AS IDENTITY"
			}
		}
		if c.Nullable {
			line += " NULL"
		} else {
			line += " NOT NULL"
		}
		if c.Default != "" && !(g.t == db.PostgreSQL && c.Identity) {
			line += " DEFAULT " + c.Default
		}
		lines = append(lines, line)
	}
	if len(g.m.PrimaryKey) > 0 {
		pk := "    PRIMARY KEY (" + g.quoteList(g.m.PrimaryKey) + ")"
		if g.m.PrimaryName != "" && g.t != db.MySQL {
			pk = "    CONSTRAINT " + g.quote(g.m.PrimaryName) + " PRIMARY KEY (" + g.quoteList(g.m.PrimaryKey) + ")"
		}
		lines = append(lines, pk)
	}
	return fmt.Sprintf("CREATE TABLE %s (\n%s\n);%s", g.table(), strings.Join(lines, ",\n"), g.batchEnd())
}

func orOne(v int64) int64 {
	if v == 0 {
		return 1
	}
	return v
}

func (g gen) indexes() string {
	var out []string
	for _, ix := range g.m.Indexes {
		if ix.Definition != "" {
			out = append(out, strings.TrimSuffix(strings.TrimSpace(ix.Definition), ";")+";"+g.batchEnd())
			continue
		}
		if len(ix.Columns) == 0 {
			continue
		}
		unique := ""
		if ix.Unique {
			unique = "UNIQUE "
		}
		stmt := fmt.Sprintf("CREATE %sINDEX %s ON %s (%s)", unique, g.quote(ix.Name), g.table(), g.quoteList(ix.Columns))
		if g.t == db.SQLServer && len(ix.Included) > 0 {
			stmt += " INCLUDE (" + g.quoteList(ix.Included) + ")"
		}
		out = append(out, stmt+";"+g.batchEnd())
	}
	return strings.Join(out, "\n")
}

type fkGroup struct {
	name        string
	toSchema    string
	toTable     string
	fromColumns []string
	toColumns   []string
}

func (g gen) foreignKeys() string {
	var order []string
	groups := map[string]*fkGroup{}
	for _, fk := range g.m.ForeignKeys {
		grp, ok := groups[fk.Name]
		if !ok {
			grp = &fkGroup{name: fk.Name, toSchema: fk.ToSchema, toTable: fk.ToTable}
			groups[fk.Name] = grp
			order = append(order, fk.Name)
		}
		grp.fromColumns = append(grp.fromColumns, fk.FromColumn)
		grp.toColumns = append(grp.toColumns, fk.ToColumn)
	}
	var out []string
	for _, name := range order {
		grp := groups[name]
		out = append(out, fmt.Sprintf("ALTER TABLE %s ADD CONSTRAINT %s FOREIGN KEY (%s)\n    REFERENCES %s (%s);%s",
			g.table(), g.quote(grp.name), g.quoteList(grp.fromColumns),
			g.qualified(grp.toSchema, grp.toTable), g.quoteList(grp.toColumns), g.batchEnd()))
	}
	return strings.Join(out, "\n")
}

func (g gen) columnNames() []string {
	names := make([]string, len(g.m.Columns))
	for i, c := range g.m.Columns {
		names[i] = c.Name
	}
	return names
}

func (g gen) selectAll() string {
	cols := g.columnNames()
	if len(cols) == 0 {
		return fmt.Sprintf("SELECT *\nFROM %s;", g.table())
	}
	return fmt.Sprintf("SELECT\n    %s\nFROM %s;", strings.ReplaceAll(g.quoteList(cols), ", ", ",\n    "), g.table())
}

// where builds the WHERE clause over the primary key, or a placeholder when
// the table has none.
func (g gen) where() string {
	if len(g.m.PrimaryKey) == 0 {
		return "WHERE /* la tabla no tiene llave primaria: define la condición */ 1 = 0"
	}
	conds := make([]string, len(g.m.PrimaryKey))
	for i, c := range g.m.PrimaryKey {
		conds[i] = g.quote(c) + " = " + g.param(c)
	}
	return "WHERE " + strings.Join(conds, "\n  AND ")
}

func (g gen) selectByPK() string {
	return strings.TrimSuffix(g.selectAll(), ";") + "\n" + g.where() + ";"
}

func (g gen) insert() string {
	var cols []string
	var vals []string
	skipped := false
	for _, c := range g.m.Columns {
		if c.Identity {
			skipped = true
			continue
		}
		cols = append(cols, c.Name)
		vals = append(vals, g.param(c.Name))
	}
	if len(cols) == 0 {
		return fmt.Sprintf("INSERT INTO %s DEFAULT VALUES;", g.table())
	}
	note := ""
	if skipped {
		note = "-- Se omiten las columnas identity / auto-incrementales.\n"
	}
	return fmt.Sprintf("%sINSERT INTO %s (\n    %s\n)\nVALUES (\n    %s\n);",
		note, g.table(),
		strings.ReplaceAll(g.quoteList(cols), ", ", ",\n    "),
		strings.Join(vals, ",\n    "))
}

func (g gen) update() string {
	pk := map[string]bool{}
	for _, c := range g.m.PrimaryKey {
		pk[c] = true
	}
	var sets []string
	for _, c := range g.m.Columns {
		if pk[c.Name] || c.Identity {
			continue
		}
		sets = append(sets, g.quote(c.Name)+" = "+g.param(c.Name))
	}
	if len(sets) == 0 {
		return "-- No hay columnas actualizables (todas son llave primaria o identity)."
	}
	return fmt.Sprintf("UPDATE %s\nSET %s\n%s;", g.table(), strings.Join(sets, ",\n    "), g.where())
}

func (g gen) delete() string {
	return fmt.Sprintf("DELETE FROM %s\n%s;", g.table(), g.where())
}
