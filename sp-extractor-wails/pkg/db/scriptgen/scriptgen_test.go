package scriptgen

import (
	"strings"
	"testing"

	"sp-extractor-wails/pkg/db"
)

func sample(schema string) db.TableMeta {
	return db.TableMeta{
		Schema: schema, Name: "orders",
		Columns: []db.MetaColumn{
			{Name: "id", DataType: "int", Identity: true, IdentitySeed: 1, IdentityStep: 1},
			{Name: "customer_id", DataType: "int"},
			{Name: "note", DataType: "varchar(50)", Nullable: true, Default: "('x')"},
		},
		PrimaryKey: []string{"id"}, PrimaryName: "PK_orders",
		Indexes: []db.MetaIndex{{Name: "IX_orders_customer", Columns: []string{"customer_id"}}},
		ForeignKeys: []db.ForeignKey{
			{Name: "FK_orders_customers", ToSchema: schema, ToTable: "customers", FromColumn: "customer_id", ToColumn: "id"},
		},
	}
}

func byID(scripts []db.TableScript, id string) string {
	for _, s := range scripts {
		if s.ID == id {
			return s.SQL
		}
	}
	return ""
}

func TestSQLServer(t *testing.T) {
	s := Generate(db.SQLServer, sample("dbo"))
	create := byID(s, "create")
	for _, want := range []string{
		"CREATE TABLE [dbo].[orders]",
		"[id] int IDENTITY(1,1) NOT NULL",
		"[note] varchar(50) NULL DEFAULT ('x')",
		"CONSTRAINT [PK_orders] PRIMARY KEY ([id])",
		"GO",
	} {
		if !strings.Contains(create, want) {
			t.Errorf("create missing %q:\n%s", want, create)
		}
	}
	if got := byID(s, "fks"); !strings.Contains(got, "ALTER TABLE [dbo].[orders] ADD CONSTRAINT [FK_orders_customers] FOREIGN KEY ([customer_id])") {
		t.Errorf("bad fk script:\n%s", got)
	}
	if got := byID(s, "insert"); strings.Contains(got, "[id]") || !strings.Contains(got, "@customer_id") {
		t.Errorf("insert should skip identity:\n%s", got)
	}
	if got := byID(s, "update"); !strings.Contains(got, "WHERE [id] = @id") || strings.Contains(got, "SET [id]") {
		t.Errorf("bad update:\n%s", got)
	}
	if !strings.Contains(byID(s, "ddl"), "CREATE INDEX [IX_orders_customer]") {
		t.Errorf("ddl should include indexes")
	}
}

func TestMySQL(t *testing.T) {
	s := Generate(db.MySQL, sample("shop"))
	create := byID(s, "create")
	if !strings.Contains(create, "CREATE TABLE `orders`") || !strings.Contains(create, "`id` int AUTO_INCREMENT NOT NULL") {
		t.Errorf("bad mysql create:\n%s", create)
	}
	if strings.Contains(create, "CONSTRAINT") || strings.Contains(create, "GO") {
		t.Errorf("unexpected tokens:\n%s", create)
	}
}

func TestPostgres(t *testing.T) {
	m := sample("public")
	m.Indexes = []db.MetaIndex{{Name: "ix", Definition: "CREATE INDEX ix ON public.orders USING btree (customer_id)"}}
	s := Generate(db.PostgreSQL, m)
	if c := byID(s, "create"); !strings.Contains(c, `"id" int GENERATED BY DEFAULT AS IDENTITY NOT NULL`) {
		t.Errorf("bad pg create:\n%s", c)
	}
	if got := byID(s, "indexes"); got != "CREATE INDEX ix ON public.orders USING btree (customer_id);" {
		t.Errorf("bad pg index: %q", got)
	}
	if got := byID(s, "update"); !strings.Contains(got, `WHERE "id" = :id`) {
		t.Errorf("bad pg update:\n%s", got)
	}
}

func TestNoPrimaryKey(t *testing.T) {
	m := sample("dbo")
	m.PrimaryKey = nil
	s := Generate(db.SQLServer, m)
	if !strings.Contains(byID(s, "delete"), "1 = 0") {
		t.Errorf("delete without PK must be a safe no-op:\n%s", byID(s, "delete"))
	}
}

func TestCompositeForeignKey(t *testing.T) {
	m := sample("dbo")
	m.ForeignKeys = []db.ForeignKey{
		{Name: "FK_x", ToSchema: "dbo", ToTable: "t", FromColumn: "a", ToColumn: "x"},
		{Name: "FK_x", ToSchema: "dbo", ToTable: "t", FromColumn: "b", ToColumn: "y"},
	}
	got := byID(Generate(db.SQLServer, m), "fks")
	if strings.Count(got, "ADD CONSTRAINT") != 1 || !strings.Contains(got, "([a], [b])") || !strings.Contains(got, "([x], [y])") {
		t.Errorf("composite fk not grouped:\n%s", got)
	}
}
